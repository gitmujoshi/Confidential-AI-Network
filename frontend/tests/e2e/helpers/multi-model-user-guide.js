const fs = require('fs');
const path = require('path');
const { expect } = require('@playwright/test');
const { getBackendURL } = require('../../../load-config');
const { seedAuth, PASSWORD: NLP_PASSWORD, USERS } = require('./nlp-dp-training');

const REPO_ROOT = path.resolve(__dirname, '../../../../');
const GUIDE_ROOT = path.join(REPO_ROOT, 'docs/guides/multi-model-user-guide');
const SCREENSHOT_ROOT = path.join(GUIDE_ROOT, 'screenshots');
const PASSWORD = NLP_PASSWORD;
const BACKEND_URL = getBackendURL();

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

async function settle(page, ms = 400) {
  await page.waitForLoadState('networkidle').catch(() => {});
  await page.waitForTimeout(ms);
}

async function captureShot(page, fileName, options = {}) {
  ensureDir(SCREENSHOT_ROOT);
  const fullPage = options.fullPage !== false;
  const outPath = path.join(SCREENSHOT_ROOT, fileName);
  await settle(page, options.settleMs ?? 500);
  await page.screenshot({
    path: outPath,
    fullPage,
    animations: 'disabled',
  });
  return {
    fileName,
    relPath: `screenshots/${fileName}`,
  };
}

async function loginTdcUi(page) {
  const { token, user } = await require('./multi-model-training').login(USERS.tdc.email);
  await seedAuth(page, { token, user });
  await page.goto('/tdc/training');
  await expect(page.getByRole('heading', { name: /Training/i })).toBeVisible({ timeout: 120000 });
  return { token, user };
}

function buildMarkdown({ steps, generatedAt, results }) {
  const lines = [
    '# Multi-Model Contract & Training Guide',
    '',
    `> Auto-generated by Playwright (\`npm run test:e2e:multi-model-guide\` in \`frontend/\`).`,
    `> Screenshots refreshed: **${generatedAt}**. Prefer regenerating over hand-editing images.`,
    '',
    'This guide shows a **separate Ricardian contract** for each catalog model type the platform supports,',
    'and runs **local-docker** training for the modalities the trainer implements today.',
    '',
    '## Catalog model types',
    '',
    '| Catalog `type` | Local train track | Fixture model | Dataset | Framework / architecture |',
    '|---|---|---|---|---|',
    '| `other` | Tabular (iris / CSV) | `e2e-model-tabular-logreg` | `e2e-dataset-1` | Other / logistic-regression |',
    '| `transformer` | Text + DP-SGD | `e2e-model-nlp-distilbert` | `e2e-nlp-ag-news` | PyTorch / tiny DistilBERT |',
    '| `cnn` | Vision (TinyCNN fastDev) | `MODEL-E2E-001` | `e2e-vision-cifar` | Catalog ResNet-50; train uses TinyCNN + FakeData when `fastDevRun` |',
    '| `rnn` | Catalog only (sign) | `e2e-model-rnn-lstm` | `e2e-dataset-1` | PyTorch / lstm |',
    '| `gan` | Catalog only (sign) | `e2e-model-gan-demo` | `e2e-dataset-1` | PyTorch / dcgan |',
    '',
    '## Demo credentials',
    '',
    '| Role | Email | Password |',
    '|---|---|---|',
    `| TDC | \`${USERS.tdc.email}\` | \`${PASSWORD}\` |`,
    `| TDP | \`${USERS.tdp.email}\` | \`${PASSWORD}\` |`,
    `| TSP | \`${USERS.ccrp.email}\` | \`${PASSWORD}\` |`,
    '',
    '## Run results (this generation)',
    '',
    '| Track | Contract | Job | Status |',
    '|---|---|---|---|',
  ];

  for (const r of results || []) {
    lines.push(
      `| ${r.title} | \`${r.contractId}\` | ${r.jobId ? `\`${r.jobId}\`` : '—'} | **${r.status}** |`
    );
  }

  lines.push('', '## Happy path', '');

  steps.forEach((step, index) => {
    lines.push(`### ${index + 1}. ${step.title}`, '');
    if (step.body) lines.push(step.body, '');
    if (step.relPath) lines.push(`![${step.title}](${step.relPath})`, '');
  });

  lines.push(
    '## Related docs',
    '',
    '- [Lifecycle screenshot guide](../lifecycle-user-guide/LIFECYCLE_USER_GUIDE.md) (enterprise onboard → one NLP DP train)',
    '- [Participant onboarding & E2E lifecycle](../PARTICIPANT_ONBOARDING_AND_E2E_LIFECYCLE.md)',
    '- [Local training runtime](../../training/TDC_TRAINING_RUNTIME.md)',
    '',
    '## Regenerate',
    '',
    '```bash',
    '# Stack must be up: backend :5001, frontend :3000, Keycloak, Docker trainer image',
    'cd frontend',
    'BACKEND_URL=http://127.0.0.1:5001 npm run test:e2e:multi-model-guide',
    '```',
    '',
    'Optional cleanup afterward: `npm run cleanup:e2e-data` from repo root.',
    ''
  );

  return lines.join('\n');
}

function writeGuide({ steps, results }) {
  ensureDir(GUIDE_ROOT);
  const generatedAt = new Date().toISOString().slice(0, 10);
  const md = buildMarkdown({ steps, generatedAt, results });
  const out = path.join(GUIDE_ROOT, 'MULTI_MODEL_USER_GUIDE.md');
  fs.writeFileSync(out, md, 'utf8');
  return out;
}

module.exports = {
  GUIDE_ROOT,
  SCREENSHOT_ROOT,
  PASSWORD,
  BACKEND_URL,
  USERS,
  captureShot,
  settle,
  loginTdcUi,
  writeGuide,
};
